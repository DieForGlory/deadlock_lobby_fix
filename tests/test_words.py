"""Числа словами.

Проверяется ровно то, на чём эта задача и ломается: числа второго
десятка. 11, 12, 13, 14 кончаются на 1, 2, 3, 4, но форма у них как у
пяти -- потому что читаются они «одиннадцать», а не «один-надцать-один».
Кто пишет правило «по последней цифре», получает «11 сервера» и выдаёт
машину с головой.
"""
from __future__ import annotations

import pytest

from deadlock_lobby_fix.words import count, plural, servers, spelled

ФОРМЫ = ("сервер", "сервера", "серверов")


@pytest.mark.parametrize("число, ожидание", [
    (1, "сервер"), (2, "сервера"), (3, "сервера"), (4, "сервера"),
    (5, "серверов"), (9, "серверов"), (10, "серверов"),
    # Второй десяток -- тот самый случай.
    (11, "серверов"), (12, "серверов"), (13, "серверов"), (14, "серверов"),
    (15, "серверов"),
    # А за ним снова как обычно.
    (21, "сервер"), (22, "сервера"), (25, "серверов"),
    (31, "сервер"), (33, "сервера"),
    # Сто одиннадцать -- опять «надцать».
    (111, "серверов"), (112, "серверов"),
    (101, "сервер"), (102, "сервера"),
    (0, "серверов"),
])
def test_the_form_follows_the_last_two_digits(число, ожидание):
    assert plural(число, *ФОРМЫ) == ожидание


def test_small_numbers_are_spelled_out():
    """«Закрыл четыре сервера» -- фраза, «закрыл 4 сервера» -- отчёт."""
    assert spelled(4) == "четыре"
    assert spelled(0) == "ноль"
    assert spelled(10) == "десять"


def test_big_numbers_stay_digits():
    """Длинное число словом читается дольше, чем цифрой."""
    assert spelled(11) == "11"
    assert spelled(33) == "33"


def test_feminine_where_it_is_needed():
    """«Одна секунда», а не «один секунда»."""
    assert spelled(1, female=True) == "одна"
    assert spelled(2, female=True) == "две"
    assert spelled(1) == "один"


def test_the_whole_phrase_reads_as_speech():
    assert count(1, *ФОРМЫ) == "один сервер"
    assert count(4, *ФОРМЫ) == "четыре сервера"
    assert count(33, *ФОРМЫ) == "33 сервера"
    assert count(11, *ФОРМЫ) == "11 серверов"


def test_servers_is_the_same_thing_shorter():
    assert servers(2) == "два сервера"
    assert servers(21) == "21 сервер"
