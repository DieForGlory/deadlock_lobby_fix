"""Числа словами и согласование с ними.

Зачем отдельный модуль
----------------------
Ничто не выдаёт машину так, как «Меряю 33 кластеров» и «закрыто
кластеров — 1». В русском у существительного при числе три формы, и
выбираются они не по «больше одного», а по последним двум цифрам: 21
сервер, 22 сервера, 25 серверов, но 11 серверов и 12 серверов -- потому
что одиннадцать кончается не на «один», а на «надцать».

Правило короткое, но ошибиться в нём легко именно на этих числах, и
ошибку эту видно каждому, кто читает по-русски. Поэтому оно здесь одно
на всю программу и покрыто проверками.

И второе: маленькие числа человек проговаривает словами. «Закрыл четыре
сервера» -- это фраза, «Закрыл 4 сервера» -- строчка отчёта. Цифрой
остаётся то, что и правда число: миллисекунды, длинные счётчики.
"""
from __future__ import annotations

# До скольких включительно писать словом. Десять -- там, где счёт ещё
# держится в голове; дальше цифра читается быстрее слова.
СЛОВОМ_ДО = 10

ЧИСЛА = ("ноль", "один", "два", "три", "четыре", "пять",
         "шесть", "семь", "восемь", "девять", "десять")

# Женский род там, где он нужен: «одна секунда», а не «один секунда».
ЖЕНСКИЕ = {1: "одна", 2: "две"}


def plural(n: int, one: str, few: str, many: str) -> str:
    """Форма слова при числе n. Само число не подставляется.

        plural(1, "сервер", "сервера", "серверов")   -> "сервер"
        plural(22, ...)                               -> "сервера"
        plural(11, ...)                               -> "серверов"
    """
    n = abs(int(n))
    хвост, сотня = n % 10, n % 100
    if 11 <= сотня <= 14:
        # Одиннадцать кончается не на «один»: «одиннадцать серверов».
        return many
    if хвост == 1:
        return one
    if хвост in (2, 3, 4):
        return few
    return many


def spelled(n: int, female: bool = False) -> str:
    """Маленькое число словом, большое -- цифрой."""
    n = int(n)
    if 0 <= n <= СЛОВОМ_ДО:
        if female and n in ЖЕНСКИЕ:
            return ЖЕНСКИЕ[n]
        return ЧИСЛА[n]
    return str(n)


def count(n: int, one: str, few: str, many: str, female: bool = False) -> str:
    """Число со словом, как сказал бы человек: «четыре сервера»."""
    return f"{spelled(n, female)} {plural(n, one, few, many)}"


def servers(n: int) -> str:
    """Самое частое сочетание в этой программе."""
    return count(n, "сервер", "сервера", "серверов")
